import crypto from 'node:crypto'
import mongoose from 'mongoose'
import { Material } from '../models/Material.js'
import { WhiteboardLesson } from '../models/WhiteboardLesson.js'
import { fullText } from '../lib/chat.js'
import { generateLesson, whiteboardAvailable } from '../lib/whiteboard.js'
import { DEFAULT_PRESET, presetById, synthesize } from '../lib/tts.js'
import { AppError } from '../lib/AppError.js'

// The teacher speaks with the podcast's own default voice — Echo, from the
// Studio preset. Resolving it here instead of hard-coding the Edge name means
// the two features can never drift apart when a preset changes.
const TEACHER_VOICE = presetById(DEFAULT_PRESET).hosts.echo.voice

/** What a lesson looks like to the client. The list omits the steps. */
function toClient(doc, { full = false } = {}) {
  const base = {
    id: String(doc._id),
    title: doc.title,
    subject: doc.subject,
    summary: doc.summary,
    question: doc.question,
    source: doc.source,
    materialId: doc.material ? String(doc.material) : '',
    materialTitle: doc.materialTitle || '',
    steps: (doc.steps || []).length,
    createdAt: doc.createdAt,
  }
  if (!full) return base
  return {
    ...base,
    steps: (doc.steps || []).map((s) => ({
      title: s.title,
      say: s.say,
      lines: (s.lines || []).map((l) => ({ kind: l.kind, text: l.text })),
    })),
    answer: { text: doc.answer?.text || '', say: doc.answer?.say || '' },
  }
}

/** GET /api/whiteboard — the student's lessons, newest first. */
export async function list(req, res) {
  const lessons = await WhiteboardLesson.find({ owner: req.user._id })
    .sort({ updatedAt: -1 })
    .limit(40)
    .select('title subject summary question source material materialTitle steps createdAt updatedAt')
    .lean()

  res.set('Cache-Control', 'private, no-store')
  res.json({ lessons: lessons.map((l) => toClient(l)) })
}

/** GET /api/whiteboard/:id — one lesson, with every step. */
export async function show(req, res, next) {
  if (!mongoose.Types.ObjectId.isValid(req.params.id)) return next(new AppError(404, 'That lesson no longer exists'))
  const lesson = await WhiteboardLesson.findOne({ _id: req.params.id, owner: req.user._id }).lean()
  if (!lesson) return next(new AppError(404, 'That lesson no longer exists'))

  res.set('Cache-Control', 'private, no-store')
  res.json(toClient(lesson, { full: true }))
}

/**
 * POST /api/whiteboard — teach a question.
 *
 * The lesson is generated by Gemini (typed questions and photographs alike)
 * and saved, so the rail on the page can reopen it without another AI call.
 * An optional material grounds the explanation in the student's own notes; the
 * text is read here and never trusted from the client.
 */
export async function create(req, res, next) {
  const { question = '', image = '', subject = '', materialId = '' } = req.body

  if (!whiteboardAvailable()) {
    return next(new AppError(503, 'The whiteboard needs an AI key. Add AI_API_KEY to the server .env and restart.'))
  }

  let material = null
  let context = ''
  if (materialId) {
    if (!mongoose.Types.ObjectId.isValid(materialId)) return next(new AppError(404, 'Material not found'))
    material = await Material.findOne({ _id: materialId, owner: req.user._id }).select('+sourceText').lean()
    if (!material) return next(new AppError(404, 'Material not found'))
    context = fullText(material)
  }

  let lesson
  try {
    lesson = await generateLesson({ question, image, subject, context })
  } catch (err) {
    console.error('Whiteboard lesson failed:', err.message)
    if (err.quota) {
      return next(new AppError(429, 'Echo has used up its AI quota for now. Wait a minute and try again.'))
    }
    if (err.name === 'TimeoutError' || err.name === 'AbortError') {
      return next(new AppError(504, 'That lesson took too long to write. Try a shorter question.'))
    }
    if (/no readable image|Nothing to teach/i.test(err.message)) {
      return next(new AppError(400, 'That photo could not be read. Try again with a clearer picture, or type the question.'))
    }
    return next(new AppError(502, 'Echo could not write that lesson just now. Try again in a moment.'))
  }

  const saved = await WhiteboardLesson.create({
    owner: req.user._id,
    title: lesson.title,
    subject: lesson.subject,
    summary: lesson.summary,
    question: String(question || '').trim().slice(0, 4000),
    source: image ? 'photo' : 'typed',
    material: material?._id,
    materialTitle: material?.title || '',
    steps: lesson.steps,
    answer: lesson.answer,
  })

  res.status(201).json({ lesson: toClient(saved, { full: true }) })
}

/**
 * GET /api/whiteboard/:id/audio/:index — record one step and send it as MP3.
 *
 * This is the same free Edge voice the podcast uses (see lib/tts.js), so the
 * teacher sounds exactly like Echo does in an episode. Recording a step happens
 * the first time it is played; the response is cached by the browser for good,
 * and the ETag lets a repeat request skip synthesis entirely. Nothing is stored
 * on disk: a lesson stays a few kilobytes of text.
 */
export async function audio(req, res, next) {
  const { id, index } = req.params
  if (!mongoose.Types.ObjectId.isValid(id)) return next(new AppError(404, 'That lesson no longer exists'))

  const lesson = await WhiteboardLesson.findOne({ _id: id, owner: req.user._id }).lean()
  if (!lesson) return next(new AppError(404, 'That lesson no longer exists'))

  const at = Number(index)
  const step = Number.isInteger(at) && at >= 0 ? lesson.steps?.[at] : null
  if (!step) return next(new AppError(404, 'That step is not part of this lesson'))

  // The final step also says the answer, exactly as the teacher strip displays
  // it, so the closing sentence is heard rather than only read.
  const isLast = at === (lesson.steps?.length || 1) - 1
  const text = [step.say || step.title, isLast ? lesson.answer?.say : ''].filter(Boolean).join(' ').trim()
  if (!text) return next(new AppError(422, 'That step has nothing to read out.'))

  const etag = `"${crypto.createHash('sha1').update(`${TEACHER_VOICE}|${text}`).digest('hex').slice(0, 20)}"`
  if (req.headers['if-none-match'] === etag) {
    res.set('ETag', etag)
    return res.status(304).end()
  }

  try {
    const mp3 = await synthesize({ voice: TEACHER_VOICE, text })
    res.set({
      'Content-Type': 'audio/mpeg',
      'Content-Length': String(mp3.length),
      // A step's audio is a pure function of its text and voice: private to this
      // account, but safe to keep in the browser for as long as it likes.
      'Cache-Control': 'private, max-age=604800, immutable',
      ETag: etag,
    })
    res.send(mp3)
  } catch (err) {
    if (err.unavailable) {
      // Edge's free voices rate-limit bursts; this is temporary.
      res.set('Retry-After', '5')
      return next(new AppError(503, 'Echo’s voice needs a few seconds. Try that step again.'))
    }
    next(err)
  }
}

/** DELETE /api/whiteboard/:id — forget one lesson. */
export async function remove(req, res, next) {
  if (!mongoose.Types.ObjectId.isValid(req.params.id)) return next(new AppError(404, 'That lesson no longer exists'))
  const removed = await WhiteboardLesson.findOneAndDelete({ _id: req.params.id, owner: req.user._id })
  if (!removed) return next(new AppError(404, 'That lesson no longer exists'))
  res.json({ ok: true })
}
