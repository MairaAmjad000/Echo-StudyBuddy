import { useCallback, useEffect, useRef, useState } from 'react'
import PageHeader from '../components/ui/PageHeader.jsx'
import SelectField from '../components/ui/SelectField.jsx'
import EmptyState from '../components/ui/EmptyState.jsx'
import Button from '../components/ui/Button.jsx'
import ChatThread from '../components/chat/ChatThread.jsx'
import ChatComposer from '../components/chat/ChatComposer.jsx'
import ChatHistory from '../components/chat/ChatHistory.jsx'
import useMaterialSelection from '../hooks/useMaterialSelection.js'
import useMediaQuery from '../hooks/useMediaQuery.js'
import useDocumentTitle from '../hooks/useDocumentTitle.js'
import { useApp } from '../store/AppContext.jsx'
import { chatErrorStory } from '../components/mascot/scenarios.js'
import '../styles/pages.css'
import '../components/chat/chat.css'

const MAX_QUESTION = 2000

/**
 * Chat with Echo. The student picks one of their materials and talks about it:
 * every answer is generated by Gemini from that material's own text, so the
 * conversation stays inside what they uploaded. Conversations are stored on the
 * server, so the rail on the left can reopen any of them later.
 */
export default function ChatEcho() {
  useDocumentTitle('Chat with Echo')
  const { actions } = useApp()
  const { ready, material, setMaterial } = useMaterialSelection()
  const [chats, setChats] = useState([])
  const [messages, setMessages] = useState([])
  const [sessionId, setSessionId] = useState(null)
  const [draft, setDraft] = useState('')
  const [busy, setBusy] = useState(false)
  const [error, setError] = useState('')
  // The history rail is a workspace panel. On a wide screen it sits beside the
  // conversation; on anything narrower it would squeeze the chat, so it waits
  // behind the History button and slides over the chat instead.
  const wideEnough = useMediaQuery('(min-width: 1200px)')
  const [showHistory, setShowHistory] = useState(wideEnough)
  const historyChosen = useRef(false)

  // Follow the breakpoint until the student picks for themselves.
  useEffect(() => {
    if (!historyChosen.current) setShowHistory(wideEnough)
  }, [wideEnough])

  const toggleHistory = () => {
    historyChosen.current = true
    setShowHistory((v) => !v)
  }

  // History is a nicety: if it cannot be fetched the chat itself still works.
  const refresh = useCallback(async () => {
    try {
      setChats(await actions.listChats())
    } catch {
      /* keep whatever list we already had */
    }
  }, [actions])

  useEffect(() => {
    refresh()
  }, [refresh])

  // Reopening a stored conversation switches material too, and that must NOT
  // count as "the student changed material" — otherwise the thread we just
  // loaded would be wiped by the reset below.
  const keepThreadFor = useRef(null)

  // Switching material starts a fresh conversation: the old answers belong to
  // the old notes.
  useEffect(() => {
    if (keepThreadFor.current === material?.id) {
      keepThreadFor.current = null
      return
    }
    setMessages([])
    setSessionId(null)
    setDraft('')
    setError('')
  }, [material?.id])

  if (!material) {
    return (
      <>
        <PageHeader title="Chat with Echo" subtitle="Talk through your notes, one question at a time." />
        <EmptyState title="Nothing to chat about yet." action={<Button to="/app/materials">Upload your first notes</Button>}>
          Upload a file first, then pick it here and ask Echo anything about it.
        </EmptyState>
      </>
    )
  }

  const sections = material.pack.sections || []
  const suggestions = [
    sections[0] && `What is ${sections[0].title} about?`,
    sections[1] && `Quiz me on ${sections[1].title}`,
    'Summarise this material in five lines',
  ].filter(Boolean)

  const send = async (text) => {
    const question = (text ?? draft).trim().slice(0, MAX_QUESTION)
    if (!question || busy) return
    setError('')
    setDraft('')

    const thread = [...messages, { role: 'user', content: question }]
    setMessages(thread)
    setBusy(true)

    try {
      const { reply, sessionId: storedId } = await actions.askEcho(material.id, thread, sessionId)
      setMessages((m) => [...m, { role: 'echo', content: reply }])
      setSessionId(storedId)
      refresh()
    } catch (e) {
      setError(e.message)
    } finally {
      setBusy(false)
    }
  }

  const newChat = () => {
    setMessages([])
    setSessionId(null)
    setDraft('')
    setError('')
  }

  const openChat = async (id) => {
    if (busy) return
    setError('')
    setDraft('')
    try {
      const stored = await actions.loadChat(id)
      const known = ready.some((m) => m.id === stored.materialId)
      keepThreadFor.current = known ? stored.materialId : null
      if (known && stored.materialId !== material.id) setMaterial(stored.materialId)
      setSessionId(stored.id)
      setMessages(stored.messages.map((m) => ({ role: m.role, content: m.content })))
    } catch (e) {
      setError(e.message)
    }
  }

  const removeChat = async (id) => {
    if (busy) return
    try {
      await actions.deleteChat(id)
      if (id === sessionId) newChat()
      setChats((list) => list.filter((c) => c.id !== id))
    } catch (e) {
      setError(e.message)
    }
  }

  return (
    <div className="chat-page">
      <PageHeader title="Chat with Echo" subtitle="Echo answers from the material you pick, not from the wider internet." />

      <div className={`chat-shell${showHistory ? '' : ' is-solo'}`}>
        {showHistory && (
          <ChatHistory chats={chats} activeId={sessionId} onOpen={openChat} onDelete={removeChat} onNew={newChat} busy={busy} />
        )}

        <section className="chat">
          <header className="chat-head">
            <SelectField
              label="Material"
              value={material.id}
              onChange={(id) => setMaterial(id)}
              options={ready.map((m) => ({ value: m.id, label: m.title }))}
            />
            <div className="chat-head-side">
              <span className="chat-head-note small muted">
                {sessionId ? 'Saved to your history.' : 'Answers are saved to your history as you go.'}
              </span>
              <button
                type="button"
                className="btn btn-quiet chat-history-toggle"
                onClick={toggleHistory}
                aria-expanded={showHistory}
              >
                {showHistory ? 'Hide history' : `History${chats.length ? ` (${chats.length})` : ''}`}
              </button>
            </div>
          </header>

          <ChatThread
            messages={messages}
            busy={busy}
            suggestions={suggestions}
            onSuggest={send}
            error={chatErrorStory(error)?.line || error}
            greeting={`Hi, I'm Echo. Ask me anything about \u201c${material.title}\u201d \u2014 I answer from your own notes, not the wider internet.`}
          />

          <ChatComposer
            value={draft}
            onChange={setDraft}
            onSend={send}
            busy={busy}
            hint="Enter sends, Shift+Enter adds a line."
          />
        </section>
      </div>
    </div>
  )
}
